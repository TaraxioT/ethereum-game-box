// Writes `src/names/abis.ts` from the forge build in `contracts/out`, so no ABI is ever written by hand.
// Run `pnpm contracts:build` first, then `pnpm --filter @egb/shared abis` (or `pnpm names:abis` at the root).

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const out = fileURLToPath(new URL('../../../contracts/out/', import.meta.url));
const target = fileURLToPath(new URL('../src/names/abis.ts', import.meta.url));

// export name -> [source file, contract name] in contracts/out
const sources: Record<string, [string, string]> = {
  gameBoxNamesAbi: ['GameBoxNames.sol', 'GameBoxNames'],
  playerStatsAbi: ['PlayerStats.sol', 'PlayerStats'],
  boxResultsAbi: ['BoxResults.sol', 'BoxResults'],
  demoLicencesAbi: ['DemoLicences.sol', 'DemoLicences'],
  boxSeatsAbi: ['BoxSeats.sol', 'BoxSeats'],
  championshipsAbi: ['Championships.sol', 'Championships'],
  duelPotAbi: ['DuelPot.sol', 'DuelPot'],
  storePotAbi: ['StorePot.sol', 'StorePot'],
  fakeUsdcAbi: ['FakeUSDC.sol', 'FakeUSDC'],
  p256AccountAbi: ['P256Account.sol', 'P256Account'],
  p256AccountFactoryAbi: ['P256AccountFactory.sol', 'P256AccountFactory'],
  permissionedRegistryAbi: ['IENSv2.sol', 'IPermissionedRegistry'],
  permissionedResolverAbi: ['IENSv2.sol', 'IPermissionedResolver'],
  resolverProfilesAbi: ['IENSv2.sol', 'IResolverProfiles'],
  verifiableFactoryAbi: ['IENSv2.sol', 'IVerifiableFactory'],
  universalResolverAbi: ['IENSv2.sol', 'IUniversalResolver'],
};

const parts = Object.entries(sources).map(([name, [file, contract]]) => {
  const artifact = JSON.parse(readFileSync(`${out}${file}/${contract}.json`, 'utf8')) as { abi: unknown[] };
  return `/** \`${contract}\` (\`contracts/out/${file}\`). */\nexport const ${name} = ${JSON.stringify(artifact.abi, null, 2)} as const;\n`;
});

writeFileSync(
  target,
  `// Generated by \`packages/shared/scripts/abis.ts\` from \`contracts/out\`. Do not edit.\n\n${parts.join('\n')}`,
);
console.log(`wrote ${Object.keys(sources).length} ABIs to ${target}`);
